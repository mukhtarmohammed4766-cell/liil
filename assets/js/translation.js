function getLifeOSLanguage() {
    return document.documentElement.lang === "ar" ? "ar" : "en";
}

window.applyLifeOSTranslations = function (root = document) {
    const dictionary = lifeOSTranslations[getLifeOSLanguage()];

    const elements = [];

    if (root.nodeType === Node.ELEMENT_NODE &&
        root.matches("[data-i18n], [data-i18n-placeholder]")) {
        elements.push(root);
    }

    if (root.querySelectorAll) {
        elements.push(...root.querySelectorAll(
            "[data-i18n], [data-i18n-placeholder]"
        ));
    }

    elements.forEach(element => {
        const key = element.getAttribute("data-i18n");
        const placeholderKey = element.getAttribute("data-i18n-placeholder");

        if (key && dictionary[key] !== undefined) {
            // Preserve icons and child elements.
            const textNode = Array.from(element.childNodes).find(
                node => node.nodeType === Node.TEXT_NODE && node.nodeValue.trim()
            );

            if (textNode) {
                textNode.nodeValue = dictionary[key];
            } else if (element.children.length === 0) {
                element.textContent = dictionary[key];
            }
        }

        if (placeholderKey && dictionary[placeholderKey] !== undefined) {
            element.setAttribute("placeholder", dictionary[placeholderKey]);
        }

        if (key && element.tagName === "INPUT" &&
            ["button", "submit"].includes(element.type) &&
            dictionary[key] !== undefined) {
            element.value = dictionary[key];
        }
    });
};

window.applyLifeOSLanguage = function (language) {
    const isArabic = language === "Arabic" || language === "ar";

    document.documentElement.lang = isArabic ? "ar" : "en";
    document.documentElement.dir = isArabic ? "rtl" : "ltr";
    document.body.dataset.language = isArabic ? "ar" : "en";

    window.applyLifeOSTranslations(document);

    if (typeof window.updateCurrentDate === "function") {
        window.updateCurrentDate();
    }
};

window.applyLifeOSTheme = function (theme) {
    const isLight = theme === "light" || theme === "Light";

    document.body.classList.toggle("light-theme", isLight);
    document.body.classList.toggle("dark-theme", !isLight);
};

